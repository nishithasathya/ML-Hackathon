"""Command-line entry point for dataset exploration.

Usage (from the repository root):
    python -m src.data_exploration.run_eda
    python -m src.data_exploration.run_eda --partitions train --data-root /path/to/data

Outputs (default outputs/eda/):
    inventory.csv            one row per trip: file existence, sizes, line counts
    inventory_summary.csv    per-partition totals
    validation_issues.csv    one row per (trip, issue) found by validation.py
    trip_statistics.csv      one row per trip: track / network / route statistics
    partition_summary.csv    describe() of the main statistics per partition
    data_quality_notes.md    generated list of anomalous trips (rules below)
"""
from __future__ import annotations

import argparse
from pathlib import Path
from typing import List

import pandas as pd

from src.common.config import ALLOWED_PARTITIONS, get_output_dir
from src.data_exploration.inventory import build_inventory, summarise_inventory
from src.data_exploration.statistics import compute_trip_statistics, partition_summary
from src.data_exploration.validation import validate_partitions

# (column, comparison, threshold, description) - thresholds are reporting choices, not model parameters.
ANOMALY_RULES = [
    ("max_gap_s", ">", 300, "largest GPS time gap above 5 minutes"),
    ("gps_route_dist_median_m", ">", 30, "median GPS distance to reference route above 30 m"),
    ("route_continuity_breaks", ">", 0, "reference route has disconnected consecutive arcs"),
    ("n_steps_speed_gt_70mps", ">", 0, "implied speed above 70 m/s (252 km/h) between consecutive fixes"),
    ("n_duplicate_timestamps", ">", 0, "duplicate consecutive timestamps"),
    ("t_start", "!=", 1, "track does not start at t = 1"),
]


def to_markdown_table(frame: pd.DataFrame) -> str:
    """Minimal markdown table writer (avoids the optional 'tabulate' dependency)."""
    def fmt(value) -> str:
        return f"{value:.4g}" if isinstance(value, float) else str(value)
    header = "| " + " | ".join(str(c) for c in frame.columns) + " |"
    divider = "|" + "|".join("---" for _ in frame.columns) + "|"
    body = ["| " + " | ".join(fmt(v) for v in row) + " |" for row in frame.itertuples(index=False)]
    return "\n".join([header, divider] + body)


def find_anomalies(stats: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for column, op, threshold, description in ANOMALY_RULES:
        if column not in stats.columns:
            continue
        mask = stats[column] > threshold if op == ">" else stats[column] != threshold
        for _, rec in stats[mask].iterrows():
            rows.append({"partition": rec["partition"], "trip_id": rec["trip_id"], "rule": description,
                         "column": column, "value": rec[column]})
    return pd.DataFrame(rows, columns=["partition", "trip_id", "rule", "column", "value"])


def write_quality_notes(path: Path, inv_summary: pd.DataFrame, issues: pd.DataFrame,
                        stats: pd.DataFrame, anomalies: pd.DataFrame) -> None:
    lines: List[str] = ["# Data-quality notes (generated by run_eda.py)", "",
                        "All numbers below were computed from the raw files by this script.", "",
                        "## Inventory", "", to_markdown_table(inv_summary), "",
                        "## Validation issue counts (number of trips affected / total occurrences)", ""]
    if issues.empty:
        lines.append("No validation issues found.")
    else:
        agg = issues.groupby(["severity", "file", "code"]).agg(trips_affected=("trip_id", "nunique"),
                                                               total_count=("count", "sum")).reset_index()
        lines.append(to_markdown_table(agg))
    lines += ["", "## Anomalous trips by rule", ""]
    if anomalies.empty:
        lines.append("No trip triggered an anomaly rule.")
    else:
        for rule, group in anomalies.groupby("rule", sort=False):
            listing = ", ".join(f"{r.partition}/{r.trip_id} ({r.value:g})" for r in group.itertuples())
            lines.append(f"* **{rule}** - {len(group)} trip(s): {listing}")
    lines += ["", "## Geographic spread", "",
              f"Trip centres span longitude {stats['center_lon'].min():.2f} to {stats['center_lon'].max():.2f} "
              f"and latitude {stats['center_lat'].min():.2f} to {stats['center_lat'].max():.2f}.",
              f"Maximum equirectangular projection error over all trips: "
              f"{stats['projection_max_rel_error'].max() * 100:.4f}% of step length.", ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description="PathSnap dataset exploration")
    parser.add_argument("--data-root", default=None, help="folder containing train/ and student_test/")
    parser.add_argument("--output-dir", default=None, help="default: outputs/eda")
    parser.add_argument("--partitions", nargs="+", default=list(ALLOWED_PARTITIONS), choices=ALLOWED_PARTITIONS)
    args = parser.parse_args(argv)

    out = Path(args.output_dir) if args.output_dir else get_output_dir("eda")
    out.mkdir(parents=True, exist_ok=True)

    print("[1/3] Building file inventory ...")
    inventory = build_inventory(args.partitions, args.data_root)
    inv_summary = summarise_inventory(inventory)
    inventory.to_csv(out / "inventory.csv", index=False)
    inv_summary.to_csv(out / "inventory_summary.csv", index=False)
    print(inv_summary.to_string(index=False))

    print("[2/3] Validating trips ...")
    issues = validate_partitions(args.partitions, args.data_root)
    issues.to_csv(out / "validation_issues.csv", index=False)
    print(f"  {len(issues)} issue rows across {issues['trip_id'].nunique() if len(issues) else 0} trips")

    print("[3/3] Computing per-trip statistics ...")
    stats = compute_trip_statistics(args.partitions, args.data_root, verbose=True)
    stats.to_csv(out / "trip_statistics.csv", index=False)
    partition_summary(stats).to_csv(out / "partition_summary.csv", index=False)

    anomalies = find_anomalies(stats)
    anomalies.to_csv(out / "anomalies.csv", index=False)
    write_quality_notes(out / "data_quality_notes.md", inv_summary, issues, stats, anomalies)
    print(f"Done. Outputs written to {out}")


if __name__ == "__main__":
    main()
